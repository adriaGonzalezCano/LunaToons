"""Generates Assets/Scripts/OrbitalSim/Rk8Coefficients.cs from SciPy's Dormand-Prince 8(5,3) tableau (DOP853).
Only the 12-stage 8th-order propagation weights are used (no step-size control, no dense output).
Run: python3 -I tools/gen_rk8_coefficients.py"""
import scipy.integrate._ivp.dop853_coefficients as d

N = 12


def lit(x):
    return repr(float(x))


lines = []
lines.append("// <auto-generated> by tools/gen_rk8_coefficients.py from SciPy's DOP853 tableau. Do not edit by hand. </auto-generated>")
lines.append("namespace Apollo.OrbitalSim")
lines.append("{")
lines.append("    /// <summary>Dormand-Prince 8th-order Runge-Kutta tableau (12 stages), as published for DOP853 (Hairer, Norsett, Wanner).</summary>")
lines.append("    internal static class Rk8Coefficients")
lines.append("    {")
lines.append(f"        public const int Stages = {N};")
lines.append("")
lines.append("        /// <summary>Stage times as fractions of the step.</summary>")
lines.append("        public static readonly double[] C = {")
lines.append("            " + ", ".join(lit(d.C[i]) for i in range(N)))
lines.append("        };")
lines.append("")
lines.append("        /// <summary>Weights of the 8th-order solution.</summary>")
lines.append("        public static readonly double[] B = {")
lines.append("            " + ", ".join(lit(d.B[i]) for i in range(N)))
lines.append("        };")
lines.append("")
lines.append("        /// <summary>Stage coefficients: A[i][j] for j &lt; i (explicit method).</summary>")
lines.append("        public static readonly double[][] A = {")
for i in range(N):
    row = ", ".join(lit(d.A[i, j]) for j in range(i))
    lines.append(f"            new double[] {{ {row} }},")
lines.append("        };")
lines.append("    }")
lines.append("}")
open('/home/claude/apollo/Assets/Scripts/OrbitalSim/Rk8Coefficients.cs', 'w').write("\n".join(lines) + "\n")
print("written; stages", N, "sum(B) =", sum(float(x) for x in d.B[:N]))
